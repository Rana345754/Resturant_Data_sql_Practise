--Find the total quality of food sold for each category wise
select Food_Category, count(*) as total_food_order, sum(Quantity) as total_quantity from [dbo].[Food_Sales_data] group by Food_Category;


--find the average rating of all orders
select Round(avg(Rating),2) as avg_Rating from [dbo].[Food_Sales_data];


-- 9.find the top 10 most expensive food items based on unit price
select distinct top 10 Food_Item,Unit_Price from [dbo].[Food_Sales_data] order by Unit_Price desc;


--10. Find the total sales amount for each food category
select Food_Category, sum(Quantity * Unit_Price) as Total_sales from [dbo].[Food_Sales_data] group by Food_Category order by Total_sales desc;


--11.Display customer Name along with their orders
select c.Customer_Name, f.Order_ID,f.Food_Item from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] f on c.Customer_ID = f.Customer_ID;


--12. Display Customer name,city,food item and order type
select c.Customer_Name,c.City,f.Food_Item,f.Order_Type from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] f on c.Customer_ID = f.Customer_ID;


--13. Find total sales generated by each customer
select c.Customer_Name,sum(f.Quantity * f.Unit_Price) as Total_Sale from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] f on c.Customer_ID = f.Customer_ID group by c.Customer_Name;


-- Q14: Find the top 10 customers based on total sales

SELECT TOP 10
    c.Customer_Name,
    SUM(f.Quantity * f.Unit_Price) AS Total_Sale
FROM [dbo].[Customers_data] c
INNER JOIN [dbo].[Food_Sales_data] f
    ON c.Customer_ID = f.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name
ORDER BY Total_Sale DESC;


--15. Find total sales by customer city
select c.City, sum(f.Quantity * f.Unit_Price) as Total_Sales from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] f on c.Customer_ID = f.Customer_ID group by City;


--16. Find the average order values fro each customer segment
select c.Customer_Segment,sum(f.Quantity * f.Unit_Price) * 1.0 / count(distinct(f.Order_ID)) as average_order_value from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] f on c.Customer_ID = f.Customer_ID group by Customer_Segment;


--17. find customers who have placed more than 5 orders
select c.Customer_Name,count(distinct(f.order_ID)) as customer_count from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] f on c.Customer_ID = f.Customer_ID group by Customer_Name having Count(f.Order_ID) > 5


--18. Find the most popular food item based on total quantity sold
select  Food_Item,sum(Quantity) as total_quantity from [dbo].[Food_Sales_data] group by Food_Item order by total_quantity desc;



--19. Find the highest spending customer using a CTE
with highest_cust_cte as (
select c.Customer_Name,c.Customer_ID,sum(s.Quantity * s.Unit_Price) as high_spending_customer from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] s on c.Customer_ID = s.Customer_ID group by c.Customer_ID,c.Customer_Name
)
select top 10 Customer_Name,high_spending_customer from highest_cust_cte order by high_spending_customer desc;


--20. Rank customers based on their total sales
with Rank_based_sale_cte as (
select c.Customer_Name,c.Customer_ID,sum(s.Quantity * s.Unit_Price) as Total_sale from [dbo].[Customers_data] c
inner join [dbo].[Food_Sales_data] s on c.Customer_ID = s.Customer_ID group by c.Customer_ID,c.Customer_Name
)
select Customer_ID,Customer_Name,Total_sale,
DENSE_RANK() over(order by Total_Sale desc) as Customer_rank from Rank_based_sale_cte order by Customer_rank;